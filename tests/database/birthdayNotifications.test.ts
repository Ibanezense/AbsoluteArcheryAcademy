import { readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { expect, it } from 'vitest'

it('generates a stored day once, adjusts only edited students and isolates annual closures and roles', async () => {
  const db = new PGlite()
  const id = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`
  try {
    await db.exec(readFileSync('tests/database/fixtures/birthdayNotifications.bootstrap.sql', 'utf8'))
    await db.exec(readFileSync('supabase/migrations/20261021024214_academy_notifications.sql','utf8'))
    await db.exec(readFileSync('supabase/migrations/20261028120000_student_birthday_notifications.sql','utf8'))
    await db.query("INSERT INTO profiles VALUES($1,'admin',true),($2,'student',true),($3,'student',true),($4,'guardian',true),($5,'admin',false)", [id(1),id(2),id(3),id(4),id(5)])
    await db.query("INSERT INTO students VALUES($1,'Birthday student',((now() AT TIME ZONE 'America/Lima')::date-interval '15 years')::date,'active',$2,false),($3,'Other student',null,'paused',$4,false)", [id(10),id(2),id(11),id(3)])
    await db.query('INSERT INTO student_guardians VALUES($1,$2)',[id(10),id(4)])
    const actor = async (n: number) => db.exec(`SELECT set_config('test.actor','${id(n)}',false); SET ROLE authenticated;`)
    const owner = async () => db.exec('RESET ROLE')
    await actor(2)
    const feed = async () => (await db.query<{data:any}>('SELECT get_student_notification_feed($1) data',[id(10)])).rows[0].data
    expect((await feed()).birthday_ready).toBe(false)
    const prep = (await db.query<{data:any}>('SELECT prepare_student_birthday_day($1) data',[id(10)])).rows[0].data
    expect(prep.ready).toBe(true)
    const first = await feed()
    expect(first.birthday.source).toBe('birthday')
    expect(first.birthday.id).toBe(`birthday:${id(10)}:${first.birthday.celebration_year}`)
    expect(first.calendar.valid_for_ms).toBeGreaterThan(0)
    await expect(db.query('SELECT ensure_student_birthday_day()')).rejects.toThrow('permission denied')
    await expect(db.query('SELECT * FROM student_birthday_days')).rejects.toThrow('permission denied')
    await expect(db.query('SELECT get_student_notification_feed($1)',[id(11)])).rejects.toThrow('acceso')
    await expect(db.query('SELECT prepare_student_birthday_day($1)',[id(11)])).rejects.toThrow('acceso')
    await owner()
    const completed = (await db.query('SELECT * FROM student_birthday_days')).rows
    await db.query('SELECT ensure_student_birthday_day()')
    expect((await db.query('SELECT * FROM student_birthday_days')).rows).toEqual(completed)
    // No second sweep: remove a stored member directly, then ensure must not put it back.
    await db.query('DELETE FROM student_birthday_day_students WHERE student_id=$1',[id(10)])
    await db.query('SELECT ensure_student_birthday_day()')
    expect((await db.query('SELECT count(*)::int n FROM student_birthday_day_students')).rows[0]).toEqual({n:0})
    await db.query('UPDATE students SET date_of_birth=date_of_birth WHERE id=$1',[id(10)])
    expect((await db.query('SELECT count(*)::int n FROM student_birthday_day_students')).rows[0]).toEqual({n:1})
    await actor(2)
    const birthday=first.birthday
    const close=async () => db.query<{data:any}>('SELECT dismiss_student_birthday($1,$2,$3) data',[id(10),birthday.celebration_year,birthday.celebration_on])
    expect((await close()).rows[0].data.already_closed).toBe(false)
    expect((await close()).rows[0].data.already_closed).toBe(true)
    expect((await feed()).birthday).toBe(null)
    await actor(1)
    const flags=(await db.query<{data:any}>('SELECT get_admin_student_birthday_flags($1) data',[[id(10),id(10),id(11)]])).rows[0].data
    expect(flags.students).toHaveLength(2)
    expect(flags.students.find((x:any)=>x.student_id===id(10)).is_birthday_today).toBe(true)
    await owner()
    await db.query("UPDATE students SET operational_status='inactive' WHERE id=$1",[id(10)])
    expect((await db.query('SELECT count(*)::int n FROM student_birthday_day_students')).rows[0]).toEqual({n:0})
    await actor(1)
    expect((await db.query<{data:any}>('SELECT get_admin_student_birthday_flags($1) data',[[id(10)]])).rows[0].data.students[0].is_birthday_today).toBe(false)
    await owner()
    await db.query("UPDATE students SET operational_status='expired' WHERE id=$1",[id(10)])
    await actor(2)
    expect((await feed()).birthday).toBe(null) // closure remains annual
    await owner()
    await db.query('DELETE FROM student_birthday_dismissals')
    await db.query("UPDATE students SET date_of_birth=date_of_birth+1 WHERE id=$1",[id(10)])
    await actor(2)
    expect((await feed()).birthday).toBe(null)
    await expect(close()).rejects.toThrow('BIRTHDAY_NOT_CURRENT')
    await owner()
    await db.query("UPDATE students SET date_of_birth=(now() AT TIME ZONE 'America/Lima')::date-interval '15 years' WHERE id=$1",[id(10)])
    await actor(4)
    expect((await feed()).birthday.source).toBe('birthday')
    await owner()
    await db.query('UPDATE students SET date_of_birth=null WHERE id=$1',[id(10)])
    await actor(2)
    expect((await feed()).birthday).toBe(null)
    await owner()
    await db.query("UPDATE students SET date_of_birth=(now() AT TIME ZONE 'America/Lima')::date+1 WHERE id=$1",[id(10)])
    expect((await db.query('SELECT count(*)::int n FROM student_birthday_day_students')).rows[0]).toEqual({n:0})
    await actor(5)
    await expect(db.query('SELECT prepare_student_birthday_day()')).rejects.toThrow('acceso')
    await expect(db.query('SELECT get_admin_student_birthday_flags(ARRAY[]::uuid[])')).rejects.toThrow('acceso')
    await owner()
    await db.exec('SET ROLE anon')
    await expect(db.query('SELECT prepare_student_birthday_day()')).rejects.toThrow('permission denied')
    await owner()
    await db.query("UPDATE students SET date_of_birth=(now() AT TIME ZONE 'America/Lima')::date-interval '20 years' WHERE id=$1",[id(11)])
    await actor(3)
    expect((await db.query<{data:any}>('SELECT get_student_notification_feed($1) data',[id(11)])).rows[0].data.birthday.source).toBe('birthday')
    await owner()
    // A targeted edit must not regenerate another student's deliberately removed projection.
    await db.query('DELETE FROM student_birthday_day_students WHERE student_id=$1',[id(11)])
    await db.query('UPDATE students SET date_of_birth=null WHERE id=$1',[id(10)])
    expect((await db.query('SELECT count(*)::int n FROM student_birthday_day_students')).rows[0]).toEqual({n:0})
    await actor(1)
    await expect(db.query('SELECT get_admin_student_birthday_flags(NULL)')).rejects.toThrow('Identificadores')
    await expect(db.query('SELECT get_admin_student_birthday_flags($1)',[Array(501).fill(id(10))])).rejects.toThrow('Identificadores')
    await owner()
    await expect(db.query("UPDATE students SET date_of_birth='2026-02-30' WHERE id=$1",[id(10)])).rejects.toThrow()
    await db.exec('BEGIN')
    const beforeZone=(await db.query('SELECT birthday_server_calendar() value')).rows[0]
    await db.exec("SET TIME ZONE 'Pacific/Kiritimati'")
    expect((await db.query('SELECT birthday_server_calendar() value')).rows[0]).toEqual(beforeZone)
    await db.exec('COMMIT')
    await db.exec(readFileSync('supabase/migrations/20261028120000_student_birthday_notifications.sql','utf8'))
    const cases=[['2000-02-29','2027-02-28','2027-02-28'],['2000-02-29','2028-02-29','2028-02-29'],['2000-02-29','2100-02-28','2100-02-28'],['1980-02-29','2000-02-29','2000-02-29'],[null,'2026-10-28',null],['2027-10-28','2026-10-28',null],['infinity','2026-10-28',null]]
    for(const [born,reference,expected] of cases) expect((await db.query<{value:string|null}>('SELECT birthday_anniversary($1::date,$2::date)::text value',[born,reference])).rows[0].value).toBe(expected)
    expect((await db.query("SELECT provolatile FROM pg_proc WHERE oid='get_student_notification_feed(uuid)'::regprocedure")).rows[0]).toEqual({provolatile:'s'})
  } finally { await db.close() }
}, 20000)
